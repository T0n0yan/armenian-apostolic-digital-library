import assert from "node:assert/strict";
import test from "node:test";

import { formatClergy } from "../app/utils/clergy-titles";

test("ծառայողների տողերը ստանում են դիմելաձև", () => {
  const typed = [
    "• Թեմի Առաջնորդ՝ Գերաշնորհ Տ. Սիոն արքեպիսկոպոս Ադամյան",
    "• Ծիսակատար Քահանա՝ Արժանապատիվ Տ. Ահարոն քհն. Գրիգորյան",
    "• Սարկավագ՝ Կարեն Առաքելյան",
    "Դպիր: Արմեն Սարգսյան, Գոռ Պետրոսյան",
    "Քահանա՝ Վահան Մելքոնյան",
    "• Սպասավոր՝ Միշա Մուրադյան",
  ].join("\n");
  assert.equal(formatClergy(typed), [
    "• Թեմի Առաջնորդ՝ Գերաշնորհ Տ. Սիոն արքեպիսկոպոս Ադամյան",
    "• Ծիսակատար Քահանա՝ Արժանապատիվ Տ. Ահարոն քհն. Գրիգորյան",
    "• Սարկավագ՝ Բարեշնորհ Կարեն սրկ. Առաքելյան",
    "Դպիր՝ Քաղցրաշնորհ Արմեն դպր. Սարգսյան, Քաղցրաշնորհ Գոռ դպր. Պետրոսյան",
    "Քահանա՝ Արժանապատիվ Տ. Վահան քհն. Մելքոնյան",
    "• Սպասավոր՝ Միշա Մուրադյան",
  ].join("\n"));
  assert.equal(formatClergy(formatClergy(typed)), formatClergy(typed));
});

test("շեշտով (`) գրված և վերջակետով տողը նույնպես ճանաչվում է", () => {
  assert.equal(formatClergy("Սարկավագ ` Կարեն Առաքելյան։"), "Սարկավագ՝ Բարեշնորհ Կարեն սրկ. Առաքելյան");
  assert.equal(formatClergy("Հոգևոր հովիվ ` Արժանապատիվ Տ. Տաթև քհն. Կիրակոսյան։"), "Հոգևոր հովիվ՝ Արժանապատիվ Տ. Տաթև քհն. Կիրակոսյան");
});
