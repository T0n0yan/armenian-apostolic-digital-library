/** Կանոն՝ այդպես է սահմանված, ավանդույթ՝ բարի սովորություն, սնահավատություն՝ սխալ պատկերացում։ */
export type RuleKind = "canon" | "tradition" | "superstition";

export type EtiquetteRule = {
  id: string;
  kind: RuleKind;
  title: string;
  /** Ինչ անել (սնահավատության համար՝ ինչպես է իրականում)։ */
  what: string;
  /** Ինչու է այդպես։ */
  why?: string;
};

export type EtiquetteTopic = {
  slug: string;
  letter: string;
  title: string;
  /** Մեկ տող՝ բաժնի քարտի և էջի նկարագրության համար։ */
  description: string;
  /** Ամփոփումը էջի վերևում։ */
  summary?: string;
  rules: EtiquetteRule[];
  faq?: Array<{ q: string; a: string }>;
  /** soon՝ դեռ գրված չէ, review՝ գրված է, սպասում է ստուգման, ready՝ ստուգված է։ */
  status: "soon" | "review" | "ready";
  /** Որտեղից է վերցված (էջի ներքևում)։ */
  sources?: string[];
};

